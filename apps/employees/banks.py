def normalize_iban(value: str) -> str:
    """«IR12 3456 …» یا ۲۴ رقم خالی → «IR» + ۲۴ رقم.

    کاربر شبا را از اپ بانک کپی می‌کند و معمولاً فاصله و خط تیره همراهش می‌آید؛
    رد کردن ورودی به‌خاطر فاصله، ایرادِ فرم است نه ایرادِ کاربر.
    """
    from apps.payroll.utils import ARABIC_INDIC

    text = (value or "").translate(ARABIC_INDIC)
    text = "".join(ch for ch in text if ch.isalnum()).upper()
    if not text:
        return ""
    if text.isdigit() and len(text) == 24:
        text = f"IR{text}"
    return text


def iban_checksum_ok(iban: str) -> bool:
    """کنترل رقم کنترلی شبا (استاندارد ISO 13616، باقی‌ماندهٔ ۹۷).

    شبای غلط روی فیش چاپ می‌شود و بعداً کسی با آن پول می‌فرستد؛ گرفتن غلط
    تایپی همین‌جا ارزان‌تر از گرفتنش در بانک است.
    """
    if len(iban) != 26 or not iban.startswith("IR") or not iban[2:].isdigit():
        return False
    rearranged = iban[4:] + iban[:4]
    digits = "".join(
        str(ord(ch) - 55) if ch.isalpha() else ch for ch in rearranged
    )
    return int(digits) % 97 == 1
